'use client';

/**
 * ═══════════════════════════════════════════════════════════════════
 * usePresence — چرخه‌حیات قطعیِ لایه‌های شناور (مودال / منو / بک‌دراپ)
 *
 * چرا این هوک وجود دارد (ریشه‌ی باگِ «قفل‌شدن صفحه پس از بستن مودال»):
 *
 *   حذفِ لایه از DOM پس از پایان انیمیشنِ خروج قبلاً به AnimatePresenceِ
 *   framer-motion v11 سپرده شده بود — کتابخانه‌ای که برای React 19 نوشته
 *   نشده است. bookkeepingِ تکمیلِ خروجِ آن (رهگیری پایانِ انیمیشنِ تمام
 *   فرزندان + سیگنال onExitComplete) زیر رندرهای هم‌زمانِ React 19 —
 *   مخصوصاً وقتی زیردرختِ در‌حال‌خروج از یک استورِ خارجی
 *   (useSyncExternalStore، مثل سشنِ فلوی احراز هویت) تغذیه شود — می‌تواند
 *   سیگنال پایان را گم کند. نتیجه: عنصرِ fixedِ تمام‌صفحه برای همیشه در
 *   DOM می‌ماند؛ چشم چیزی نمی‌بیند (شفاف است) اما هر کلیک روی همان لایه
 *   می‌نشیند → «صفحه لاک شده و هیچ دکمه‌ای کار نمی‌کند».
 *
 * فلسفه‌ی طراحی (الگوی استاندارد صنعت — Radix / Headless UI):
 *
 *   تخلیه‌ی لایه به هیچ رویدادِ انیمیشنی (animationend/transitionend)
 *   و هیچ callbackِ کتابخانه‌ای وابسته نیست؛ فقط به setTimeout بومیِ
 *   مرورگر — که مرورگر اجرایش را تضمین می‌کند. انیمیشن‌های CSS صرفاً
 *   تجربه‌ی بصری‌اند؛ حیات و مرگِ لایه را ماشین‌حالتِ همین هوک تعیین
 *   می‌کند. حتی در بدترین سناریو (رویداد انیمیشن خفه‌شده، reduced-motion
 *   بدون انیمیشن، تبِ پس‌زمینه با rAF متوقف) پس از exitMs لایه قطعاً
 *   از DOM می‌رود و صفحه آزاد است.
 *
 * قرارداد:
 *   open: true → لایه بلافاصله رندر می‌ماند (بدون فلیکِ یک‌فریمی).
 *   open: false → فاز «خروج» آغاز می‌شود: کلاس‌های خروج بازی می‌کنند،
 *     مصرف‌کننده باید تعامل را قطع کند (pointer-events-none + inert).
 *     پس از exitMs لایه قطعاً unmount می‌شود.
 *   بازشدنِ میانِ فاز خروج → تایمرِ تخلیه لغو می‌شود؛ هیچ
 *     ناپدیدشدنِ دیرهنگامِ مرموزی در کار نیست. (برقراریِ مجددِ قفل
 *     اسکرول و تله‌ی فوکوس هم سازوکار استاندارد خودشان را دارند.)
 *
 * خروجی:
 *   rendered — لایه را رندر کن؟ (open || در حال خروج)
 *   closing  — در فاز خروجی؟ (برای کلاس انیمیشنِ خروج + قطعِ تعامل)
 * ═══════════════════════════════════════════════════════════════════
 */

import { useEffect, useState } from 'react';

export function usePresence(
  open: boolean,
  /** مدتِ انیمیشنِ خروج به میلی‌ثانیه — پس از این مدت، تخلیه‌ی قطعی */
  exitMs: number,
): { rendered: boolean; closing: boolean } {
  // kept = «هنوز برای تمام‌شدنِ خروج نگه داشته شده» — تک‌منبعِ حقیقت
  const [kept, setKept] = useState(open);

  useEffect(() => {
    if (open) {
      // بازشدن (یا بازشدنِ میانِ خروج: cleanupِ افکتِ قبلی تایمرِ
      // تخلیه را لغو کرده) — فقط حیات را تثبیت می‌کنیم.
      setKept(true);
      return undefined;
    }
    if (!kept) return undefined; // از قبل کاملاً بسته — کاری نیست
    const timer = window.setTimeout(() => setKept(false), Math.max(0, exitMs));
    return () => window.clearTimeout(timer);
  }, [open, kept, exitMs]);

  return {
    // open در همان کامیتِ فعلی رندر را فعال می‌کند (بدون انتظارِ effect)
    rendered: kept || open,
    closing: !open && kept,
  };
}
