/**
 * نرمال‌سازیِ پارامترِ مسیرِ داینامیک (slug) — ترمیمِ ریشه‌ایِ ۴۰۴ اسلاگ‌های فارسی.
 *
 * ریشه‌ی باگ (بازتولید + اثباتِ لایه‌به‌لایه، ۲۰۲۶-۰۹-۲۹):
 * در «next start» (سِلف‌هاستِ پروداکشن) Next.js پارامترهای مسیرِ غیر-ASCII را
 * همچنان **percent-encoded** به page/layout تحویل می‌دهد، در حالی‌که لایه‌های
 * داده‌ی ما فرضِ decodeشده‌بودن داشتند و دوباره encodeURIComponent می‌کردند:
 *
 *   مرورگر:  /lms/courses/%D8%AC%D8%A7%D9%88%D8%A7-…
 *   params:  "%D8%AC%D8%A7%D9%88%D8%A7-…"        (همچنان انکدشده!)
 *   wire:    /lms/courses/%25D8%25AC%25D8%25A7…/  (double-encode)
 *   Django:  یک لایه unquote ⇒ اسلاگِ تحت‌اللفظی «%D8%AC…» ⇒ ۴۰۴
 *
 * اسلاگ‌های ASCII چون کاراکترِ انکدشدنی ندارند، از این مسیر سالم عبور می‌کردند —
 * دقیقاً همان رفتاری که در تولید دیده شد (php ✓ / جاوا-اسکریپت ✗).
 *
 * این هلپر قراردادِ «ورودی همیشه decodeشده» را تضمین می‌کند تا کدِ پایین‌دست
 * فارغ از رفتارِ نسخه/محیطِ Next یکسان عمل کند:
 *   • ورودیِ انکدشده  ⇒ decode می‌شود.
 *   • ورودیِ decodeشده ⇒ دست‌نخورده برمی‌گردد (idempotent نیست، اما بدون ٪ِ معتبر،
 *     همان رشته است و خروجیِ دوم هم با اول یکی است — در عمل بی‌ضرر).
 *   • ٪ِ ناقص/نامعتبر ⇒ ورودیِ خام برمی‌گردد (هیچ‌وقت throw نمی‌کند).
 *
 * نکته‌ی دامنه: اسلاگ‌ها در بک‌اند SlugField هستند و نمی‌توانند «٪» داشته باشند،
 * پس بر출بودنِ %[hex][hex] در ورودیِ مسیر همیشه به معنای «انکدِ ترانزیت» است و
 * decode‌کردن هیچ داده‌ی مشروعی را خراب نمی‌کند.
 */
const ENCODED_BYTE = /%[0-9A-Fa-f]{2}/;
const MAX_DECODE_PASSES = 3;

/**
 * decodeِ حلقه‌ای تا پایدارشدن — علاوه بر ترانزیتِ تک‌لایه‌ایِ Next، لینک‌هایی که
 * مسنجرها/واسط‌ها یک لایه‌ی اضافه encode می‌کنند (٪۲۵D8…) هم خودترمیم می‌شوند.
 */
export function normalizeRouteSlug(raw: string): string {
  if (typeof raw !== 'string') return raw;
  let out = raw;
  for (let i = 0; i < MAX_DECODE_PASSES && ENCODED_BYTE.test(out); i += 1) {
    try {
      const next = decodeURIComponent(out);
      if (next === out) break;
      out = next;
    } catch {
      break; // ٪ِ ناقص/نامعتبر — هر چه تا اینجا decode شده همان خروجی است
    }
  }
  return out;
}
